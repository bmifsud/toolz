"""OpenSSH server configuration generator for Termux and Debian environments."""

from enum import Enum
import os
from pathlib import Path
from typing import Optional

try:
    from .security import SecurityError, validate_port
except ImportError:
    from security import SecurityError, validate_port


class TargetEnvironment(Enum):
    TERMUX = "termux"
    DEBIAN = "debian"


TERMUX_DEFAULT_PORT = 8022
DEBIAN_DEFAULT_PORT = 2222


def generate_sshd_config(
    env: TargetEnvironment,
    host_key_path: Path,
    authorized_keys_path: Path,
    listen_address: str = "127.0.0.1",
    port: Optional[int] = None,
    pid_file: Optional[Path] = None,
) -> str:
    """Generate a hardened, fail-closed sshd_config.

    Enforces:
    - Listen only on specified private/localhost address
    - Key authentication only (no password, no challenge-response, no keyboard-interactive)
    - StrictModes yes
    - No X11, no agent forwarding, no TCP forwarding by default unless needed
    """
    if listen_address not in ("127.0.0.1", "::1") and not listen_address.startswith(("10.", "172.", "192.168.")):
        raise SecurityError(f"listen_address must be localhost or private network; got '{listen_address}'")

    selected_port = port if port is not None else (TERMUX_DEFAULT_PORT if env == TargetEnvironment.TERMUX else DEBIAN_DEFAULT_PORT)
    validate_port(selected_port)

    # In Termux, ports < 1024 cannot be bound without root.
    if env == TargetEnvironment.TERMUX and selected_port < 1024:
        raise SecurityError(f"Termux non-root sshd cannot bind privileged port {selected_port}. Use >= 1024 (e.g. 8022).")

    lines = [
        f"# Hardened OpenSSH Server Config for {env.value.upper()}",
        "# Generated by bmifsud/toolz secure OpenSSH alternative",
        f"Port {selected_port}",
        f"ListenAddress {listen_address}",
        f"HostKey {host_key_path.resolve()}",
        f"AuthorizedKeysFile {authorized_keys_path.resolve()}",
        "",
        "# Authentication Hardening",
        "PubkeyAuthentication yes",
        "PasswordAuthentication no",
        "KbdInteractiveAuthentication no",
        "ChallengeResponseAuthentication no",
        "UsePAM no",
        "PermitRootLogin no",
        "PermitEmptyPasswords no",
        "StrictModes yes",
        "MaxAuthTries 3",
        "",
        "# Session and Forwarding Hardening",
        "AllowAgentForwarding no",
        "AllowTcpForwarding no",
        "X11Forwarding no",
        "PrintMotd no",
        "AcceptEnv LANG LC_*",
        "ClientAliveInterval 300",
        "ClientAliveCountMax 2",
    ]

    if pid_file:
        lines.append(f"PidFile {pid_file.resolve()}")

    return "\\n".join(lines) + "\\n"
